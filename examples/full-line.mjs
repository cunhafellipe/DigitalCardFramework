const [destination, ...args] = process.argv.slice(2);
assert(destination && args.length === 4, 'Usage: node examples/full-line.mjs OUTPUT --source-revision COMMIT --base-url https://host.example/content/');
const options = Object.fromEntries([0, 2].map(index => [args[index], args[index + 1]]));
assert.deepEqual(Object.keys(options).sort(), ['--base-url', '--source-revision']);
assert(/^[a-f0-9]{40}$/i.test(options['--source-revision']), 'Use the exact 40-character source commit');
