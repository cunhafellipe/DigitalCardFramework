await mkdir(output, {recursive: true});
assert.equal((await readdir(output)).length, 0, 'Output must be empty; choose a new directory');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const json = async (name, value) => writeFile(join(output, name), JSON.stringify(value, null, 2) + '\n');
await mkdir(join(output, 'sources'));
await mkdir(join(output, 'packages'));
const width = 300, height = 450, sources = [], presentations = [];
const rights = 'Original procedural geometry generated by examples/full-line.mjs; distributed under the repository MIT license. No external artwork or fonts.';

async function artwork(id, title, palette, layered = false) {
  const images = {};
  for (const [side, color] of [['front', palette[0]], ['back', palette[1]]]) {
    const data = new Uint8Array(width * height * 4);
    for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
      const inset = x > 24 && x < width - 25 && y > 24 && y < height - 25;
      const circle = (x - width / 2) ** 2 + (y - height / 2) ** 2 < (side === 'front' ? 75 : 45) ** 2;
      const pixel = (y * width + x) * 4;
      data.set(circle ? [240, 224, 170, 255] : inset ? [...color, 255] : [20, 28, 40, 255], pixel);
    }
    const bytes = await encodePNG({width, height, data}), path = `sources/${id}-${side}.png`;
    await writeFile(join(output, path), bytes);
    sources.push({path, sha256: hash(bytes), bytes: bytes.length, rights, alt: `${title}, ${side}: a gold disc on a bordered geometric field`});
    images[side] = {bytes, mediaType: 'image/png', pixels: data};
  }
  const project = createProject(await imagePackage({id, title, ...images.front, back: images.back}));
  if (layered) {
    const tileWidth = 90, tileHeight = 135, tile = new Uint8Array(tileWidth * tileHeight * 4);
    const composed = images.front.pixels.slice();
    for (let y = 0; y < tileHeight; y++) for (let x = 0; x < tileWidth; x++) {
      const source = (Math.floor(y * height / tileHeight) * width + Math.floor(x * width / tileWidth)) * 4;
      const pixel = images.back.pixels.subarray(source, source + 4);
      tile.set(pixel, (y * tileWidth + x) * 4);
      composed.set(pixel, ((y + 300) * width + x + 180) * 4);
    }
    const tileBytes = await encodePNG({width: tileWidth, height: tileHeight, data: tile});
    const inset = await project.addImage(new Blob([tileBytes], {type: 'image/png'}), {id: 'inset-art'});
    project.edit(p => {
      p.scenes.get(p.manifest.faces.front.scene).nodes.push({id: 'inset', type: 'image', asset: inset.id, x: 180, y: 300, width: tileWidth, height: tileHeight});
    });
    const poster = await encodePNG({width, height, data: composed});
    await project.setPosters({front: new Blob([poster], {type: 'image/png'})});
    const path = `sources/${id}-composed-front.png`;
    await writeFile(join(output, path), poster);
    sources.push({path, sha256: hash(poster), bytes: poster.length, rights, alt: `${title}, front with inset geometric layer`});
  }
  const pkg = await project.export();
  await writeFile(join(output, 'packages', `${id}.dcard`), pkg.archive);
  const published = await publishPackage(pkg.archive, {contentRoot: join(output, 'content')});
  assert.equal(published.digest, pkg.digest);
  const reference = {contract: 'digital-card@0.1', digest: pkg.digest, baseURL: new URL(pkg.digest.slice(7) + '/', base).href};
  const faces = Object.fromEntries(Object.entries(pkg.manifest.faces).map(([side, face]) => {
    const asset = pkg.manifest.assets.find(item => item.id === face.poster);
    return [side, {scene: face.scene, poster: asset.path, alt: face.description, url: new URL(asset.path, reference.baseURL).href}];
  }));
  presentations.push({id, title, reference, archive: `packages/${id}.dcard`, sha256: hash(pkg.archive), faces, layered});
  return {pkg, reference, faces};
}

const dawn = await artwork('dawn', 'Geometry Dawn', [[40, 90, 140], [35, 55, 90]], true);
const dusk = await artwork('dusk', 'Geometry Dusk', [[115, 50, 120], [60, 40, 80]]);
const jacket = await artwork('jacket', 'Geometry Pack', [[40, 110, 95], [30, 65, 60]]);
const book = await artwork('book', 'Geometry Album', [[110, 75, 40], [70, 50, 35]]);
const catalog = validateCatalog({
  version: 1,
  capabilities: {version: 1, preset: 'packCollection', primitives: {issuance: true, settlement: true}},
  features: {publicAlbums: true},
  currencies: [{id: 'credits', name: 'Credits', value: {numerator: 1, denominator: 1}, tradable: false}],
  lines: [{id: 'geometry', name: 'Geometry Line'}],
  rarities: [{id: 'common', name: 'Common', rank: 0}],
  cards: ['dawn', 'dusk'].map(id => ({id, lineId: 'geometry', name: `Geometry ${id === 'dawn' ? 'Dawn' : 'Dusk'}`, description: 'Original procedural geometry.'})),
  variants: ['dawn', 'dusk'].map(id => ({id: `${id}.standard`, cardId: id, rarityId: 'common', finish: 'standard'})),
  products: [{id: 'geometry.pack', lineId: 'geometry', name: 'Geometry Pair', revision: 1, price: {currencyId: 'credits', amount: 10},
    slots: ['dawn', 'dusk'].map(id => ({count: 1, pool: [{variantId: `${id}.standard`, weight: 1}]})),
    artwork: {front: jacket.faces.front.url, back: jacket.faces.back.url, alt: 'Green geometric pack with a gold disc', design: jacket.reference}}],
});
const release = {
  version: 1, key: 'geometry-line-v1', publicBaseURL: base.href, catalog,
  cards: [{id: 'dawn', title: 'Geometry Dawn', file: 'packages/dawn.dcard'}, {id: 'dusk', title: 'Geometry Dusk', file: 'packages/dusk.dcard'}],
};
await json('release.json', release);

// The shipped CLI rebuilds the emitted card inputs; no test-only publisher is used.
const cli = fileURLToPath(new URL('../src/presentation/creator-cli.mjs', import.meta.url));
const cliOutput = execFileSync(process.execPath, [cli, join(output, 'release.json'), join(output, 'cli-verification')], {encoding: 'utf8', timeout: 30000});
await writeFile(join(output, 'cli-result.json'), cliOutput);
const prepared = JSON.parse(cliOutput), publishedCatalog = JSON.parse(await readFile(join(output, 'cli-verification', 'catalog.json'), 'utf8'));
assert.deepEqual(prepared.digests, [dawn.pkg.digest, dusk.pkg.digest]);
const creator = createAuthoring({validateCatalog,
  publish: async pkg => ({contract: 'digital-card@0.1', digest: (await publishPackage(pkg.archive, {contentRoot: join(output, 'content')})).digest, baseURL: new URL(pkg.digest.slice(7) + '/', base).href}),
  commitCatalog: async next => {await json('catalog.json', next); return {state: 'prepared'};},
});
const built = await creator.publishPack({key: release.key, catalog, cards: [dawn, dusk].map(({pkg}) => ({id: pkg.manifest.id, title: pkg.manifest.title, source: {format: 'dcard', bytes: pkg.archive}}))});
assert.deepEqual(built.digests, prepared.digests);
assert.deepEqual(built.catalog, publishedCatalog);

const layout = {pageSize: 2, artwork: {
  cover: {src: book.faces.front.url, alt: 'Brown geometric album cover', design: book.reference},
  spine: {src: book.faces.back.url, alt: 'Brown geometric album spine', design: book.reference},
  pages: [{id: 'pair', title: 'Geometry Pair', src: book.faces.back.url, alt: 'A page holding the two geometric cards', design: book.reference}],
}};
await json('album-layout.json', layout);
for (const item of presentations) {
  const decoded = await importPackage(new Uint8Array(await readFile(join(output, item.archive))));
  assert.equal(decoded.digest, item.reference.digest);
  for (const [side, face] of Object.entries(item.faces)) {
    assert(decoded.files.has(face.scene) && decoded.files.has(face.poster));
    assert.equal(decoded.manifest.faces[side].description, face.alt);
  }
}

const core = new CardFramework({store: new MemoryStore()});
let acquisition;
try {
  const admin = {role: 'admin'};
  core.publishCatalog(admin, built.catalog);
  const collector = core.registerUser(admin, {provider: 'example', subject: 'geometry-collector', displayName: 'Example collector'}), actor = {userId: collector.id};
  core.grantCurrency(admin, {userId: collector.id, currencyId: 'credits', amount: 10, key: 'initial', reason: 'Fictional example balance'});
  const input = {...core.quote(actor, {productId: 'geometry.pack', quantity: 1}), key: 'pair-purchase'};
  const purchased = core.purchase(actor, input), opening = {packId: purchased.packs[0].id, key: 'pair-open'}, opened = core.openPack(actor, opening);
  assert.deepEqual(core.purchase(actor, input), purchased);
  assert.deepEqual(core.openPack(actor, opening), opened);
  assert.equal(core.wallet(actor).credits, 0);
  assert.equal(core.inventory(actor).length, 2);
  assert.deepEqual(new Set(opened.cards.map(copy => copy.definition.id)), new Set(['dawn', 'dusk']));
  for (const copy of opened.cards) assert.equal(copy.definition.presentation.digest, built.catalog.cards.find(card => card.id === copy.definition.id).presentation.digest);
  assert.equal(purchased.packs[0].product.artwork.design.digest, jacket.pkg.digest);
  const album = core.saveAlbum(actor, {key: 'pair-album', name: 'Geometry Album', visibility: 'public', layout,
    placements: opened.cards.map((copy, position) => ({copyId: copy.id, position, data: {pageId: 'pair'}}))});
  const viewed = core.viewAlbum(actor, album.id);
  assert.equal(viewed.cards.length, 2);
  assert.deepEqual(viewed.layout, layout);
  assert(core.audit(admin).ok);
  acquisition = {cards: 2, packs: 1, albums: 1, spent: 10, balance: 0, replayUnchanged: true, purchaseReceipt: purchased, openingReceipt: opened, albumId: album.id};
} finally {core.close();}

