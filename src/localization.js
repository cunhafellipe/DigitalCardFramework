/** Select display text without changing the diagnostic or its retry identity. */
export function localizeDiagnostic(localization,error){
  // Uncoded local validation messages retain compatibility, including caller-authored text.
  if(!error?.code&&error?.name!=='SyntaxError'&&typeof error?.message==='string')return error.message;
  const key=error?.name==='SyntaxError'?'diagnostic.input':Object.hasOwn(diagnosticKeys,error?.code)?diagnosticKeys[error.code]:'diagnostic.unknown';
  return localization.text(key);
}
